export const DESCRIPTION = '更新任务列表中的任务'

export const PROMPT = `使用此工具更新任务列表中的任务。

## 何时使用此工具

**将任务标记为已解决：**
- 当你完成了任务中描述的工作
- 当任务不再需要或已被取代
- 重要提示：完成分配的任务后，始终将其标记为已解决
- 解决后，调用 TaskList 查找下一个任务

- 只有在完全完成任务时才将其标记为已完成
- 如果遇到错误、阻碍或无法完成，保持任务为 in_progress
- 被阻塞时，创建一个新任务描述需要解决的问题
- 在以下情况下绝不将任务标记为已完成：
  - 测试失败
  - 实现不完整
  - 遇到未解决的错误
  - 找不到必要的文件或依赖项

**删除任务：**
- 当任务不再相关或被错误创建时
- 将状态设为 \`deleted\` 会永久删除该任务

**更新任务详情：**
- 当需求改变或变得更明确时
- 在任务之间建立依赖关系时

## 可更新的字段

- **status**：任务状态（见下方状态工作流）
- **subject**：更改任务标题（祈使式，例如"运行测试"）
- **description**：更改任务描述
- **activeForm**：任务处于 in_progress 时在进度条中显示的进行时形式（例如"正在运行测试"）
- **owner**：更改任务所有者（代理名称）
- **metadata**：将元数据键合并到任务中（将键设为 null 可删除它）
- **addBlocks**：标记在此任务完成之前无法开始的任务
- **addBlockedBy**：标记必须在此任务开始之前完成的任务

## 状态工作流

状态进展：\`pending\` → \`in_progress\` → \`completed\`

使用 \`deleted\` 永久删除任务。

## 数据过时问题

在更新任务之前，请确保使用 \`TaskGet\` 读取任务的最新状态。

## 示例

开始工作时将任务标记为进行中：
\`\`\`json
{"taskId": "1", "status": "in_progress"}
\`\`\`

完成工作后将任务标记为已完成：
\`\`\`json
{"taskId": "1", "status": "completed"}
\`\`\`

删除任务：
\`\`\`json
{"taskId": "1", "status": "deleted"}
\`\`\`

通过设置所有者认领任务：
\`\`\`json
{"taskId": "1", "owner": "my-name"}
\`\`\`

设置任务依赖关系：
\`\`\`json
{"taskId": "2", "addBlockedBy": ["1"]}
\`\`\`
`
